// The exact remover has to observe raw inode identity across a rename, which
// only the node fs primitives expose; `FileSystem` cannot express it.
// @effect-diagnostics nodeBuiltinImport:off
// Cleanup and lease stores expose promise-facing ports, so recovery runs them
// against the SQL client captured before entering those callbacks.
// @effect-diagnostics runEffectInsideEffect:off
// Startup recovery reads lease expiry inside promise callbacks, where there is
// no fiber to carry an Effect Clock.
// @effect-diagnostics globalDate:off
